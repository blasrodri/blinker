#!/usr/bin/env python3
"""Generate the S0 fixtures and describe the five edit classes.

Why generated fixtures for small, and real crates for medium and large
---------------------------------------------------------------------

V2 §4 asks for five *edit classes*, and an edit class is a claim about what
the compiler must redo. Making that claim precisely — "this edit introduces
exactly one new monomorphization and nothing else" — is only possible in a
crate written for the purpose. So `small` is generated.

But a generated crate cannot answer the question S0 exists to answer, because
the frontend's cost is dominated by the size of the crate graph it has to
validate against, and a generated crate has none. So `medium` and `large` are
real projects, edited in place through the same edit classes wherever the
class is expressible there.

The edits are anchored, not positional
--------------------------------------

Every edit is a literal `(anchor, replacement)` pair on a file's text, applied
to the *pristine* source each time rather than to whatever the last edit left
behind. An edit sequence that composes is an edit sequence whose later members
measure something other than what they name.
"""

import argparse
import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Enough functions that the crate is not a toy, few enough that it builds in
# under a second: the point of `small` is a floor on frontend cost, not a
# second medium fixture.
HELPERS = 300

SMALL_LIB = """//! Generated by fixtures.py. Do not edit by hand.

/// A type whose layout the hot root depends on, so that edit class 5 has
/// something to change.
#[derive(Clone, Copy)]
pub struct Reading {{
    pub value: u64,
    pub scale: u32,
}}

impl Reading {{
    pub fn total(&self) -> u64 {{
        self.value.wrapping_mul(self.scale as u64)
    }}
}}

{helpers}

/// Generic, and instantiated below at `u64` only. Edit class 3 asks for it at
/// a second type, which is a new monomorphization and nothing else.
pub fn convert<T: Into<u64> + Copy>(x: T) -> u64 {{
    x.into().wrapping_add(1)
}}

/// The hot root. `#[inline(never)]` because a replaceable boundary that the
/// optimizer may erase is not one (V2 §10.3).
#[inline(never)]
pub fn hot_root(reading: Reading) -> u64 {{
    {body}
}}

/// A second caller, so the hot root is not the only user of the helpers and
/// removing a call from it does not make a helper dead.
pub fn secondary(reading: Reading) -> u64 {{
    helper_17(reading.value)
        .wrapping_add(helper_128(reading.value))
        .wrapping_add(convert(reading.value))
}}

pub fn entry(value: u64) -> u64 {{
    let reading = Reading {{ value, scale: 3 }};
    hot_root(reading).wrapping_add(secondary(reading))
}}

/// A binary, not a library. A library crate has no monomorphization roots —
/// its generics are instantiated by whoever uses it — so whole-crate
/// collection over one finds nothing and Path C would be measuring an empty
/// set. The first run of this spike reported `whole_crate_mono_items: 0` for
/// a 300-function crate, which is the shape of that mistake.
fn main() {{
    let n = std::env::args().count() as u64;
    println!("{{}}", entry(n));
}}
"""

BASE_BODY = "reading.total().wrapping_mul(7).wrapping_add(1)"

# The five classes of V2 §4. Each names what the compiler is being asked to
# redo, which is the thing the measurement is about.
EDITS = {
    # 1. Arithmetic only. No new callee, no new instance, no layout change.
    #    This is the cheapest edit that is still a real edit, and the floor
    #    for any latency claim.
    "body_arith": "reading.total().wrapping_mul(11).wrapping_add(2)",
    # 2. Calls a function that is already monomorphized and already reachable,
    #    so the mono closure gains nothing and only the root's MIR changes.
    "body_existing_call": "helper_17(reading.total()).wrapping_add(3)",
    # 3. Introduces `convert::<u32>`, which did not exist in the previous
    #    build. The mono closure grows by exactly one item.
    "body_new_generic": "convert(reading.value as u32).wrapping_mul(5)",
    # 4. The signature changes, so every caller's codegen is invalid even
    #    though no caller's source changed. Expected to leave the fast lane.
    "signature": None,  # handled specially: rewrites the fn line and callers
    # 5. A type's layout changes, which invalidates every function that
    #    touches a value of it. The control that must be classified L3.
    "type_layout": None,  # handled specially: rewrites the struct
}


def small(root: Path):
    helpers = "\n".join(
        f"#[inline(never)]\npub fn helper_{i}(x: u64) -> u64 {{ "
        f"x.wrapping_mul({2 * i + 3}).wrapping_add({i}) }}"
        for i in range(HELPERS)
    )
    crate = root / "small"
    src = crate / "src"
    src.mkdir(parents=True, exist_ok=True)
    (crate / "Cargo.toml").write_text(
        '[package]\nname = "spike-small"\nversion = "0.0.0"\nedition = "2021"\n'
        "\n[[bin]]\nname = \"spike_small\"\npath = \"src/main.rs\"\n\n[workspace]\n"
    )
    (src / "main.rs").write_text(SMALL_LIB.format(helpers=helpers, body=BASE_BODY))
    return crate


def variants(pristine: str) -> dict:
    """Every edit class as a complete file text, from the pristine one."""
    out = {"pristine": pristine}
    for name, body in EDITS.items():
        if body is not None:
            out[name] = pristine.replace(BASE_BODY, body)
    # A signature change: one more parameter, and the callers that must follow.
    out["signature"] = (
        pristine.replace(
            "pub fn hot_root(reading: Reading) -> u64 {",
            "pub fn hot_root(reading: Reading, bias: u64) -> u64 {",
        )
        .replace(BASE_BODY, f"{BASE_BODY}.wrapping_add(bias)")
        .replace("hot_root(reading).wrapping_add", "hot_root(reading, 9).wrapping_add")
    )
    # A layout change: a field added in the middle, so offsets move rather
    # than the struct merely growing at the end.
    out["type_layout"] = pristine.replace(
        "pub value: u64,\n    pub scale: u32,",
        "pub value: u64,\n    pub tag: u64,\n    pub scale: u32,",
    ).replace("Reading {{ value, scale: 3 }}".replace("{{", "{").replace("}}", "}"),
              "Reading { value, tag: 0, scale: 3 }")
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(HERE / "fixtures"))
    options = parser.parse_args()
    root = Path(options.out)
    root.mkdir(parents=True, exist_ok=True)

    crate = small(root)
    pristine = (crate / "src" / "main.rs").read_text()
    made = variants(pristine)
    # Written beside the fixture rather than applied: the driver picks one per
    # revision, and a variant that is only ever produced at run time cannot be
    # inspected when a number looks wrong.
    store = crate / "variants"
    if store.exists():
        shutil.rmtree(store)
    store.mkdir()
    for name, text in made.items():
        (store / f"{name}.rs").write_text(text)

    manifest = {
        "name": "small",
        "crate": str(crate),
        "file": "src/main.rs",
        "crate_name": "spike_small",
        "crate_type": "bin",
        "hot": "hot_root",
        "variants": sorted(made),
    }
    (crate / "fixture.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"  small: {HELPERS} helpers, {len(made) - 1} edit variants -> {crate}")


if __name__ == "__main__":
    main()
