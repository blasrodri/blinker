#!/usr/bin/env python3
"""The S0c adversarial suite: prove the classifier refuses what it must.

A classifier that says DIRECT to everything passes the five edit classes of
S0 and is worthless. What has to be shown is the opposite property — that
edits which *look* body-only but are observable downstream are refused — and
that requires cases built to fool it.

Each case names a function and an expected verdict. A case that produces the
wrong verdict fails; a case that produces the right verdict *for the wrong
reason* also fails, because the reason is what the product will show a user
and what a future change will regress against.

The dangerous direction is asymmetric. A false FALLBACK costs a rebuild. A
false DIRECT ships a program in which the old code is still running somewhere,
and no test the developer writes will find it. So every case whose expected
verdict is DIRECT is one this suite has to justify, and every FALLBACK is
cheap.
"""

import argparse
import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent

CRATE = '''//! Generated by adversarial.py. Do not edit by hand.
#![allow(dead_code, unused_variables, clippy::all)]

use std::fmt::Debug;

#[derive(Clone, Copy)]
pub struct Reading {
    pub value: u64,
    pub scale: u32,
}

impl Reading {
    #[inline(never)]
    pub fn total(&self) -> u64 {
        self.value.wrapping_mul(self.scale as u64)
    }
}

#[inline(never)]
pub fn helper(x: u64) -> u64 {
    x.wrapping_mul(31).wrapping_add(7)
}

pub fn convert<T: Into<u64> + Copy>(x: T) -> u64 {
    x.into().wrapping_add(1)
}

pub static SHARED: u64 = 11;
pub static OTHER: u64 = 13;

// ---------------------------------------------------------------- ordinary
// The only shape the first DIRECT class admits: a free, non-generic,
// non-const, non-async `fn` with `#[inline(never)]`.

#[inline(never)]
pub fn ordinary(reading: Reading) -> u64 {
    ORDINARY_BODY
}

// ------------------------------------------------------------ inline hint
// Identical but for `#[inline]`, which makes rustc encode the body into the
// crate metadata so downstream crates may inline their own copy. Replacing
// the function here would leave those copies running the old code.

#[inline]
pub fn inline_hinted(reading: Reading) -> u64 {
    INLINE_HINTED_BODY
}

// --------------------------------------------------------------- generic
// Monomorphized by whoever calls it, so its MIR ships in the metadata.

#[inline(never)]
pub fn generic_fn<T: Into<u64> + Copy + Debug>(x: T) -> u64 {
    GENERIC_BODY
}

// ---------------------------------------------------------------- const fn
// Callable at compile time, so rustc keeps CTFE MIR for it and a downstream
// crate may evaluate the *old* body into a constant.

#[inline(never)]
pub const fn const_fn(x: u64) -> u64 {
    CONST_BODY
}

// ------------------------------------------------------------------ async
// Its body determines the layout of the returned state machine.

#[inline(never)]
pub async fn async_fn(x: u64) -> u64 {
    ASYNC_BODY
}

// ------------------------------------------------------------ impl Trait
// The hidden type behind the opaque is part of the downstream contract.

#[inline(never)]
pub fn rpit_fn(x: u64) -> impl Iterator<Item = u64> {
    RPIT_BODY
}

// ------------------------------------------------------------ trait method
// A method's identity runs through its trait's vtable and its impl's
// coherence, neither of which the contract compares.

pub trait Compute {
    fn compute(&self, x: u64) -> u64;
}

pub struct Computer;

impl Compute for Computer {
    #[inline(never)]
    fn compute(&self, x: u64) -> u64 {
        TRAIT_METHOD_BODY
    }
}

// ------------------------------------------------------- target feature
// A codegen attribute changes the instructions rustc may emit, and is
// invisible to the signature.

TARGET_FEATURE_ATTR
#[inline(never)]
pub fn feature_fn(x: u64) -> u64 {
    x.wrapping_mul(3)
}

// ------------------------------------------------------------------ entry
// Reachability is one of the inputs to rustc's own encoding rule, so every
// candidate has to actually be reachable or the measurement is of a dead
// function.

#[unsafe(no_mangle)]
pub extern "C" fn entry(value: u64) -> u64 {
    let reading = Reading { value, scale: 3 };
    let mut total = ordinary(reading)
        .wrapping_add(inline_hinted(reading))
        .wrapping_add(generic_fn(value))
        .wrapping_add(const_fn(value))
        .wrapping_add(rpit_fn(value).sum::<u64>())
        .wrapping_add(Computer.compute(value))
        .wrapping_add(feature_fn(value))
        .wrapping_add(convert(value))
        .wrapping_add(helper(value));
    total = total.wrapping_add(SHARED);
    total
}

fn main() {
    println!("{}", entry(std::env::args().count() as u64));
}
'''

BODIES = {
    "ORDINARY_BODY": "reading.total().wrapping_mul(7).wrapping_add(1)",
    "INLINE_HINTED_BODY": "reading.total().wrapping_mul(7).wrapping_add(2)",
    "GENERIC_BODY": "x.into().wrapping_mul(7).wrapping_add(3)",
    "CONST_BODY": "x.wrapping_mul(7).wrapping_add(4)",
    "ASYNC_BODY": "x.wrapping_mul(7).wrapping_add(5)",
    "RPIT_BODY": "(0..x).map(|v| v.wrapping_mul(7))",
    "TRAIT_METHOD_BODY": "x.wrapping_mul(7).wrapping_add(6)",
    "TARGET_FEATURE_ATTR": "",
}

# name -> (hot function, expected verdict, expected reason or None, how to edit)
CASES = {
    # --- must be DIRECT -----------------------------------------------
    "ordinary_arith": ("ordinary", "DIRECT", None,
                       {"ORDINARY_BODY": "reading.total().wrapping_mul(11).wrapping_add(2)"}),
    "ordinary_existing_call": ("ordinary", "DIRECT", None,
                               {"ORDINARY_BODY": "helper(reading.total()).wrapping_add(3)"}),
    "ordinary_new_local_fn": ("ordinary", "DIRECT", None,
                              {"ORDINARY_BODY": "extra(reading.total())",
                               "__append": "\n#[inline(never)]\npub fn extra(x: u64) -> u64 "
                                           "{ x.wrapping_add(41) }\n"}),
    "ordinary_reads_existing_static": ("ordinary", "DIRECT", None,
                                       {"ORDINARY_BODY": "reading.total().wrapping_add(SHARED)"}),

    # --- must be FALLBACK, and for the stated reason -------------------
    "inline_hint": ("inline_hinted", "FALLBACK", "cross_crate_inlinable",
                    {"INLINE_HINTED_BODY": "reading.total().wrapping_mul(13)"}),
    "generic": ("generic_fn", "FALLBACK", "requires_monomorphization",
                {"GENERIC_BODY": "x.into().wrapping_mul(13)"}),
    "const_fn": ("const_fn", "FALLBACK", "const_evaluable",
                 {"CONST_BODY": "x.wrapping_mul(13)"}),
    "async_fn": ("async_fn", "FALLBACK", None,
                 {"ASYNC_BODY": "x.wrapping_mul(13)"}),
    "rpit": ("rpit_fn", "FALLBACK", "opaque_in_signature",
             {"RPIT_BODY": "(0..x).map(|v| v.wrapping_mul(13))"}),
    "trait_method": ("compute", "FALLBACK", "associated_fn",
                     {"TRAIT_METHOD_BODY": "x.wrapping_mul(13)"}),
    # The dangerous one: the diff is dominated by body text, and the signature
    # change is one word.
    "sneaky_signature": ("ordinary", "FALLBACK", "contract_changed",
                         {"__raw": [("pub fn ordinary(reading: Reading) -> u64 {",
                                     "pub fn ordinary(reading: Reading) -> u32 {"),
                                    ("ORDINARY_BODY",
                                     "reading.total().wrapping_mul(11).wrapping_add(2) as u32"),
                                    (".wrapping_add(inline_hinted(reading))",
                                     " as u64).wrapping_add(inline_hinted(reading))"),
                                    ("let mut total = ordinary(reading)",
                                     "let mut total = (ordinary(reading)")]}),
    "target_feature": ("feature_fn", "FALLBACK", "contract_changed",
                       {"TARGET_FEATURE_ATTR": '#[target_feature(enable = "aes")]',
                        "__raw": [("pub fn feature_fn(x: u64) -> u64 {",
                                   "pub unsafe fn feature_fn(x: u64) -> u64 {"),
                                  (".wrapping_add(feature_fn(value))",
                                   ".wrapping_add(unsafe { feature_fn(value) })")]}),
    "new_static": ("ordinary", "FALLBACK", None,
                   {"ORDINARY_BODY": "reading.total().wrapping_add(FRESH)",
                    "__append": "\npub static FRESH: u64 = 17;\n"}),
    # DIRECT, but only because Path D closes the new instance locally: the
    # artifact must carry `convert::<u32>` as well as `ordinary`. This is
    # V2 §9.4's patch cluster, and it is the case that proves DIRECT means
    # "replace this closure" rather than "replace this function".
    "new_generic_instantiation": ("ordinary", "DIRECT", None,
                                  {"ORDINARY_BODY":
                                   "convert(reading.value as u32).wrapping_mul(5)"}),
}


def render(bodies: dict) -> str:
    text = CRATE
    for key, value in bodies.items():
        text = text.replace(key, value)
    return text


def build(out: Path):
    crate = out / "adversarial"
    src = crate / "src"
    src.mkdir(parents=True, exist_ok=True)
    (crate / "Cargo.toml").write_text(
        '[package]\nname = "spike-adversarial"\nversion = "0.0.0"\nedition = "2021"\n'
        '\n[[bin]]\nname = "spike_adversarial"\npath = "src/main.rs"\n\n[workspace]\n'
    )
    pristine = render(BODIES)
    (src / "main.rs").write_text(pristine)

    store = crate / "variants"
    if store.exists():
        shutil.rmtree(store)
    store.mkdir()
    (store / "pristine.rs").write_text(pristine)

    expectations = {}
    for name, (hot, verdict, reason, edit) in CASES.items():
        bodies = dict(BODIES)
        append = edit.get("__append", "")
        raw = edit.get("__raw", [])
        for key, value in edit.items():
            if not key.startswith("__"):
                bodies[key] = value
        text = render(bodies) + append
        for old, new in raw:
            if old in BODIES:  # a body placeholder already substituted
                old = BODIES[old]
            if old not in text:
                raise SystemExit(f"{name}: anchor not found: {old!r}")
            text = text.replace(old, new)
        (store / f"{name}.rs").write_text(text)
        expectations[name] = {"hot": hot, "verdict": verdict, "reason": reason}

    (crate / "fixture.json").write_text(json.dumps({
        "name": "adversarial",
        "crate": str(crate),
        "file": "src/main.rs",
        "crate_name": "spike_adversarial",
        "crate_type": "bin",
        "hot": "ordinary",
        "variants": sorted(["pristine"] + list(CASES)),
        "expectations": expectations,
    }, indent=2) + "\n")
    print(f"  adversarial: {len(CASES)} cases -> {crate}")
    return crate


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(HERE / "fixtures"))
    build(Path(parser.parse_args().out))


if __name__ == "__main__":
    main()
